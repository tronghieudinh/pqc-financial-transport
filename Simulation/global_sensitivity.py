#!/usr/bin/env python3
"""
global_sensitivity.py - variance-based (Sobol-type) sensitivity on the full factorial designs.

For a full factorial with equal cell counts the first-order index of factor X is
S_X = Var(E[Y|X]) / Var(Y) and the second-order index of (X, Z) is
S_XZ = Var(E[Y|X,Z]) / Var(Y) - S_X - S_Z, computed exactly from cell means.

Responses
  wired_latency : log latency of cold transactions (all suites)
  wired_factor  : log(latency / baseline latency) for post-quantum suites, same network cell
  radio_factor  : log(mean latency / baseline mean latency) for post-quantum suites over radio
  *_lattice     : the same restricted to the lattice suites (ML-DSA, Falcon)
Also writes 95 % confidence intervals for the radio mean-latency factors (delta method from the
Monte Carlo standard errors, ignoring the positive correlation of common random numbers, i.e.
conservative).

    python3 global_sensitivity.py -> sensitivity_indices.csv, radio_factor_ci.csv
"""
import itertools
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
V2 = HERE   # results regenerated by run_all.sh
BASE = "ECDSA-P256|X25519"
PQ = ["ML-DSA-44|ML-KEM-768", "ML-DSA-65|ML-KEM-768", "ML-DSA-87|ML-KEM-1024", "Falcon-512|ML-KEM-768",
      "Falcon-1024|ML-KEM-1024", "SLH-DSA-128s|ML-KEM-768", "SLH-DSA-128f|ML-KEM-768"]


def indices(df, y, factors, response):
    v = df[y].var(ddof=0)
    rows, first = [], {}
    for f in factors:
        s = df.groupby(f)[y].mean().reindex(df[f]).to_numpy()
        first[f] = np.var(s) / v
        rows.append([response, f, "", round(first[f], 4)])
    for a, b in itertools.combinations(factors, 2):
        s = df.groupby([a, b])[y].transform("mean").to_numpy()
        s2 = np.var(s) / v - first[a] - first[b]
        rows.append([response, a, b, round(s2, 4)])
    return rows


def main():
    w = pd.read_csv(os.path.join(V2, "results", "results.csv"),
                    usecols=["suite", "protocol", "mode", "depth", "bw_mbps", "rtt_ms", "mtu", "penalty_ms", "total_ms"])
    w = w[w["mode"] == "cold"].copy()
    w["y"] = np.log(w["total_ms"])
    net = ["protocol", "depth", "bw_mbps", "rtt_ms", "mtu", "penalty_ms"]
    out = indices(w, "y", ["suite"] + net, "wired_latency")

    base = w[w["suite"] == BASE].set_index(net)["total_ms"]
    pq = w[w["suite"].isin(PQ)].copy()
    pq["y"] = np.log(pq["total_ms"].to_numpy() / base.reindex(pd.MultiIndex.from_frame(pq[net])).to_numpy())
    out += indices(pq, "y", ["suite"] + net, "wired_factor")
    lat = pq[pq["suite"].str.startswith(("ML-DSA", "Falcon"))]
    out += indices(lat, "y", ["suite"] + net, "wired_factor_lattice")

    r = pd.read_csv(os.path.join(V2, "radio_results", "radio_results.csv"))
    rb = r[r["suite"] == BASE].set_index(["profile", "sinr_db", "protocol", "mode"])
    rp = r[r["suite"].isin(PQ)].copy()
    key = pd.MultiIndex.from_frame(rp[["profile", "sinr_db", "protocol", "mode"]])
    bm = rb["mean_ms"].reindex(key).to_numpy()
    bse = (rb["std_ms"] / np.sqrt(rb["trials"])).reindex(key).to_numpy()
    rp["factor"] = rp["mean_ms"].to_numpy() / bm
    rp["y"] = np.log(rp["factor"])
    out += indices(rp, "y", ["suite", "profile", "sinr_db", "protocol", "mode"], "radio_factor")
    rl = rp[rp["suite"].str.startswith(("ML-DSA", "Falcon"))]
    out += indices(rl, "y", ["suite", "profile", "sinr_db", "protocol", "mode"], "radio_factor_lattice")
    se = rp["std_ms"] / np.sqrt(rp["trials"])
    rel = np.sqrt((se / rp["mean_ms"]) ** 2 + (bse / bm) ** 2)
    rp["ci_lo"] = rp["factor"] * (1 - 1.96 * rel)
    rp["ci_hi"] = rp["factor"] * (1 + 1.96 * rel)
    rp[["profile", "sinr_db", "protocol", "mode", "suite", "factor", "ci_lo", "ci_hi"]].round(4).to_csv(
        os.path.join(HERE, "radio_factor_ci.csv"), index=False)

    pd.DataFrame(out, columns=["response", "factor", "factor2", "index"]).to_csv(
        os.path.join(HERE, "sensitivity_indices.csv"), index=False)
    s = pd.DataFrame(out, columns=["response", "factor", "factor2", "index"])
    for resp in s["response"].unique():
        t = s[s["response"] == resp].sort_values("index", ascending=False).head(6)
        print(resp, "; ".join(f"{a}{'x' + b if b else ''}={v:.2f}" for a, b, v in t[["factor", "factor2", "index"]].values))


if __name__ == "__main__":
    main()
