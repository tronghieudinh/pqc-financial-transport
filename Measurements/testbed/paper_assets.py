#!/usr/bin/env python3
"""
paper_assets.py - numbers, table and figure of the testbed section of paper 1, straight from the raw measurements.

    python3 paper_assets.py [--latex ../../paper]

Reads every raw run in results/ (core_a, segs, segs2, knee, grid_b, cubic, proxy_tcp, proxy_inspect; missing files are
skipped), pools transactions of identical configurations, and writes into the LaTeX directory
    numbers_testbed.tex            \\newcommand values (\\input by main.tex)
    tables/tab_testbed.tex         model error per suite
    figures/fig_testbed.pdf        measured excess latency against the two model variants
"""
from __future__ import annotations

import argparse
import csv
import os
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "Simulation"))
import analyze_testbed as A  # noqa: E402
import pqc_sim as S  # noqa: E402

RAW = {"direct": ["core_a", "segs", "segs2", "knee", "grid_b"], "cubic": ["cubic"],
       "proxy": ["core_a", "proxy_tcp", "proxy_inspect"]}
WORDS = "Zero One Two Three Four Five Six Seven Eight Nine".split()


def load(names):
    rows = []
    for n in names:
        p = os.path.join(HERE, "results", n + ".csv")
        if os.path.exists(p):
            rows += A.load(p, False)
    return rows


def fmt(x, nd=1):
    return f"{x:.{nd}f}"


def write_numbers(path, nums):
    with open(path, "w") as fh:
        fh.write("% Generated by Measurements/testbed/residual_analysis.py - do not edit\n")
        for k, v in nums.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


def model_segments(c, req, resp):
    """Data segments the (stack) model sends per side: (client, server)."""
    d = int(c["depth"])
    flow = S.build_flow(c["suite"], A.probe_protocol(c["mtls"], req, resp, d), d, "cold", False)
    mss, cw = int(c["mtu"]) - 60, [int(c["icw"])] * 2
    out = [0, 0]
    for stp, w in zip([x for x in flow.steps if x[0] == "x"], flow.writes):
        n = S.segments_of_writes(w, mss, cw[stp[1]])
        out[stp[1]] += n
        cw[stp[1]] = S.grow_cwnd(cw[stp[1]], n)
    return tuple(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", default=os.path.join(HERE, "..", "..", "paper"))
    ap.add_argument("--boot", type=int, default=1000)
    a = ap.parse_args()
    os.makedirs(os.path.join(a.latex, "tables"), exist_ok=True)
    os.makedirs(os.path.join(a.latex, "figures"), exist_ok=True)
    nums = {}

    # ------------------------------------------------------------------ direct path, Reno, no loss
    rows = [r for r in load(RAW["direct"]) if r["topology"] == "direct" and r["cc"] == "reno"]
    agg = A.aggregate(rows)
    table = [t for t in A.build_table(agg, a.boot) if A.f(t["loss_pct"]) == 0]
    n_tx = sum(1 for r in rows if r["err"] == "")
    nums["tbNConfigs"] = f"{len(table)}"
    nums["tbNTrans"] = f"{n_tx:,}".replace(",", "{,}")
    nums["tbNSuites"] = f"{len({t['suite'] for t in table})}"
    err = lambda key: [t[key] - t["excess_ms"] for t in table]
    for tag, key in (("Ideal", "model_ms"), ("Linux", "model_cv_ms"), ("Stack", "model_stack_ms")):
        e = err(key)
        nums[f"tbMae{tag}"] = fmt(st.mean(abs(v) for v in e), 2)
        nums[f"tbBias{tag}"] = f"{st.mean(e):+.2f}".replace("+", "+")
        nums[f"tbMax{tag}"] = fmt(max(abs(v) for v in e), 1)
        nums[f"tbOff{tag}"] = f"{sum(abs(v) > 0.4 * A.f(t['rtt_ms']) for v, t in zip(e, table))}"
        rel = [abs(v) / t["excess_ms"] for v, t in zip(e, table) if t["excess_ms"] > 1]
        nums[f"tbRel{tag}"] = fmt(100 * st.median(rel), 1)
    off = [abs(t["model_ms"] - t["excess_ms"]) / A.f(t["rtt_ms"]) for t in table if abs(t["model_ms"] - t["excess_ms"]) > 0.4 * A.f(t["rtt_ms"])]
    nums["tbOffIdealOne"] = f"{sum(0.8 <= v <= 1.2 for v in off)}"
    nums["tbOffIdealMaxRtt"] = fmt(max(off), 1) if off else "0"

    def pick(suite, depth, rtt, mtu):
        return next((t for t in table if t["suite"] == suite and int(t["depth"]) == depth and A.f(t["rtt_ms"]) == rtt and int(t["mtu"]) == mtu
                     and int(t["req"]) < 5000), None)
    w = pick("ML-DSA-65|ML-KEM-768", 2, 30, 1500)
    if w:
        nums["tbWinMeas"], nums["tbWinIdeal"], nums["tbWinLinux"] = fmt(w["excess_ms"], 1), fmt(w["model_ms"], 1), fmt(w["model_cv_ms"], 1)
    g = pick("ML-DSA-65|ML-KEM-768", 1, 30, 1280)
    if g:
        nums["tbSegMeas"], nums["tbSegIdealMs"], nums["tbSegStackMs"] = fmt(g["excess_ms"], 1), fmt(g["model_ms"], 1), fmt(g["model_stack_ms"], 1)
    nums["tbMaxStackRtt"] = ", ".join(f"{max(abs(t['model_stack_ms'] - t['excess_ms']) for t in table if A.f(t['rtt_ms']) == r):.1f}"
                                      for r in sorted({A.f(t['rtt_ms']) for t in table}))
    # configurations away from the calibration point (rate, jumbo frames, larger initial window)
    out_ = [t for t in table if A.f(t["rate_mbps"]) != 100 or int(t["mtu"]) == 9000 or int(t["icw"]) != 10]
    if out_:
        e_i = [t["model_ms"] - t["excess_ms"] for t in out_]
        e_s = [t["model_stack_ms"] - t["excess_ms"] for t in out_]
        nums["tbOutN"] = str(len(out_))
        nums["tbOutMaeIdeal"], nums["tbOutMaeStack"] = fmt(st.mean(abs(v) for v in e_i), 2), fmt(st.mean(abs(v) for v in e_s), 2)
        nums["tbOutMax"] = fmt(max(abs(v) for v in e_s), 1)
        nums["tbOutOffIdeal"] = str(sum(abs(v) > 0.4 * A.f(t["rtt_ms"]) for v, t in zip(e_i, out_)))
        nums["tbOutOffStack"] = str(sum(abs(v) > 0.4 * A.f(t["rtt_ms"]) for v, t in zip(e_s, out_)))
        for tag, rate in (("Low", 10.0), ("High", 1000.0)):
            sel = [t["model_stack_ms"] - t["excess_ms"] for t in out_ if A.f(t["rate_mbps"]) == rate]
            if sel:
                nums[f"tbOutBias{tag}"] = f"{st.mean(sel):+.1f}"
    nums["tbWithinOne"] = f"{sum(t['stack_within_1ms'] for t in table)}"
    nums["tbInCi"] = f"{sum(t['stack_in_ci'] for t in table)}"
    nums["tbSizeLo"] = fmt(min(t["size_ratio"] for t in table), 2)
    nums["tbSizeHi"] = fmt(max(t["size_ratio"] for t in table), 2)
    nums["tbRttLo"] = fmt(min(A.f(t["rtt_ms"]) for t in table), 0)
    nums["tbRttHi"] = fmt(max(A.f(t["rtt_ms"]) for t in table), 0)
    nums["tbRates"] = ", ".join(sorted({f"{A.f(t['rate_mbps']):g}" for t in table}, key=float))
    nums["tbMtus"] = ", ".join(sorted({str(t["mtu"]) for t in table}, key=int))
    nums["tbIcws"] = ", ".join(sorted({str(t["icw"]) for t in table}, key=int))

    # kernel segment counters against the model
    seg = [t for t in table if t["segs_out"] > 0]
    exact = tot = 0
    for t in seg:
        req, resp = int(t["req"]), int(t["resp"])
        c, s = model_segments(t, req, resp)
        exact += (int(t["segs_out"]) == c) + (int(t["segs_in"]) - 1 == s)
        tot += 2
    nums["tbSegExact"], nums["tbSegTotal"] = str(exact), str(tot)
    ideal_c = [(t, S.build_flow(t["suite"], A.probe_protocol(t["mtls"], t["req"], t["resp"], t["depth"]), int(t["depth"]),
                                "cold", False)) for t in seg]
    nums["tbSegIdealExact"] = str(sum((int(t["segs_out"]) == sum(-(-x[2] // (int(t["mtu"]) - 60)) for x in f.steps if x[0] == "x" and x[1] == 0))
                                      + (int(t["segs_in"]) - 1 == sum(-(-x[2] // (int(t["mtu"]) - 60)) for x in f.steps if x[0] == "x" and x[1] == 1))
                                      for t, f in ideal_c))

    # pi / theta fit on the direct path
    rs = [t["excess_ms"] - t["model_stack_ms"] for t in table]
    best = None
    for th in range(1, 25):
        ps = [S.run_flow(S.build_flow(t["suite"], A.probe_protocol(t["mtls"], t["req"], t["resp"], t["depth"]), int(t["depth"]), "cold", False),
                         S.Net(A.f(t["rate_mbps"]), A.f(t["rtt_ms"]), int(t["mtu"]), 1.0, th, int(t["icw"])))["pen_flights"] for t in table]
        pi, sse, *_ = A.fit_pi(rs, ps)
        if best is None or sse < best[0]:
            best = (sse, th, pi)
    nums["tbRmseZeroPi"] = fmt((sum(r * r for r in rs) / len(rs)) ** 0.5, 2)
    nums["tbPiFit"], nums["tbThetaFit"] = fmt(best[2], 2), str(best[1])
    nums["tbRmseBestPi"] = fmt((best[0] / len(rs)) ** 0.5, 2)

    # SWIFT-sized request at MTU 1280: hybrid against baseline
    knee = [t for t in table if int(t["req"]) > 5000 and t["suite"] in (S.BASELINE, "ECDSA-P256|X25519MLKEM768")]
    for t in knee:
        tag = "Hyb" if "MLKEM" in t["suite"] else "Base"
        nums[f"tbKnee{tag}"] = fmt(t["excess_ms"], 1)
        nums[f"tbKnee{tag}Model"] = fmt(t["model_stack_ms"], 1)

    # ------------------------------------------------------------------ CUBIC
    crows = [r for r in load(RAW["cubic"]) if r["topology"] == "direct" and r["cc"] == "cubic"]
    if crows:
        ct = [t for t in A.build_table(A.aggregate(crows), a.boot) if A.f(t["loss_pct"]) == 0]
        if ct:
            e = [t["model_stack_ms"] - t["excess_ms"] for t in ct]
            nums["tbCubicN"] = str(len(ct))
            nums["tbCubicMae"] = fmt(st.mean(abs(v) for v in e), 2)
            nums["tbCubicOffIdeal"] = str(sum(abs(t["model_ms"] - t["excess_ms"]) > 0.4 * A.f(t["rtt_ms"]) for t in ct))
            nums["tbCubicOffStack"] = str(sum(abs(v) > 0.4 * A.f(t["rtt_ms"]) for v, t in zip(e, ct)))
            nums["tbCubicBias"] = f"{st.mean(e):+.2f}"
            nums["tbCubicMax"] = fmt(max(abs(v) for v in e), 1)

    # ------------------------------------------------------------------ real middlebox
    prows = [r for r in load(RAW["proxy"]) if r["cc"] == "reno"]
    pagg = A.aggregate(prows)
    dirs = {tuple(c[k] for k in A.KEY_BASE[1:] + A.KEY_NET): c for c in pagg.values() if c["net_id"] == "shaped" and c["topology"] == "direct"}
    for topo, tag in (("proxy-tcp", "Tcp"), ("proxy-inspect", "Inspect")):
        ds = []
        for c in pagg.values():
            if c["net_id"] == "shaped" and c["topology"] == topo:
                d = dirs.get(tuple(c[k] for k in A.KEY_BASE[1:] + A.KEY_NET))
                if d:
                    ds.append(c["med"] - d["med"])
        if ds:
            nums[f"tbProxy{tag}N"] = str(len(ds))
            nums[f"tbProxy{tag}Mean"] = fmt(st.mean(ds), 2)
            nums[f"tbProxy{tag}Lo"] = fmt(min(ds), 2)
            nums[f"tbProxy{tag}Hi"] = fmt(max(ds), 2)

    write_numbers(os.path.join(a.latex, "numbers_testbed.tex"), nums)

    # ------------------------------------------------------------------ table per suite
    short = {"RSA-2048|ECDHE-P256": "RSA-2048 / ECDHE", "ECDSA-P256|X25519": "ECDSA-P256 / X25519",
             "ECDSA-P256|X25519MLKEM768": "ECDSA-P256 / X25519MLKEM768", "ML-DSA-44|ML-KEM-768": "ML-DSA-44 / ML-KEM-768",
             "ML-DSA-65|ML-KEM-768": "ML-DSA-65 / ML-KEM-768", "ML-DSA-87|ML-KEM-1024": "ML-DSA-87 / ML-KEM-1024"}
    lines = ["\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{0.30\\textwidth}rrrr@{}}", "\\toprule",
             "\\shortstack[l]{Signature /\\\\key exchange} & \\shortstack[r]{Config-\\\\urations} & \\shortstack[r]{MAE ideal\\\\(ms)} & \\shortstack[r]{MAE stack\\\\(ms)} & "
             "\\shortstack[r]{Within\\\\1\\,ms} \\\\", "\\midrule"]
    for su in short:
        ts = [t for t in table if t["suite"] == su]
        if not ts:
            continue
        lines.append(f"{short[su]} & {len(ts)} & {st.mean(abs(t['model_ms'] - t['excess_ms']) for t in ts):.2f} & "
                     f"{st.mean(abs(t['model_stack_ms'] - t['excess_ms']) for t in ts):.2f} & "
                     f"{sum(t['stack_within_1ms'] for t in ts)} of {len(ts)} \\\\")
    lines += ["\\midrule", f"All & {len(table)} & {nums['tbMaeIdeal']} & {nums['tbMaeStack']} & {nums['tbWithinOne']} of {len(table)} \\\\",
              "\\bottomrule", "\\end{tabular}"]
    open(os.path.join(a.latex, "tables", "tab_testbed.tex"), "w").write("\n".join(lines) + "\n")

    # ------------------------------------------------------------------ figure
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, axs = plt.subplots(1, 2, figsize=(6.2, 3.7), sharex=True, sharey=True)
        cols = {"RSA-2048|ECDHE-P256": "#999999", "ECDSA-P256|X25519": "#000000", "ECDSA-P256|X25519MLKEM768": "#56B4E9",
                "ML-DSA-44|ML-KEM-768": "#009E73", "ML-DSA-65|ML-KEM-768": "#D55E00", "ML-DSA-87|ML-KEM-1024": "#CC79A7"}
        hi = max(max(t["excess_ms"], t["model_ms"], t["model_stack_ms"]) for t in table) * 1.3
        for ax, key, title in ((axs[0], "model_ms", "(a) idealised closed form"), (axs[1], "model_stack_ms", "(b) validated stack")):
            for su, c in cols.items():
                ts = [t for t in table if t["suite"] == su]
                ax.scatter([t["excess_ms"] for t in ts], [t[key] for t in ts], s=12, c=c, alpha=0.8, label=short[su], linewidths=0)
            ax.plot([2, hi], [2, hi], "k--", lw=0.7)
            ax.set_xscale("log")
            ax.set_yscale("log")
            ax.set_xlim(2, hi)
            ax.set_ylim(2, hi)
            ax.set_xlabel("measured excess latency (ms)")
            ax.set_title(title, fontsize=9)
            ax.grid(alpha=0.2)
        axs[0].set_ylabel("model transport time (ms)")
        for ax in axs:
            ax.tick_params(labelsize=8)
            ax.xaxis.label.set_size(8.5)
        axs[0].yaxis.label.set_size(8.5)
        h, l = axs[1].get_legend_handles_labels()
        fig.legend(h, l, loc="lower center", ncol=3, fontsize=7.5, frameon=False, markerscale=1.4)
        fig.tight_layout(rect=(0, 0.14, 1, 1))
        fig.savefig(os.path.join(a.latex, "figures", "fig_testbed.pdf"))
    except Exception as e:      # matplotlib is optional
        print("(no figure:", e, ")")
    print(f"{len(table)} direct configurations, {n_tx} transactions; stack MAE {nums['tbMaeStack']} ms (ideal {nums['tbMaeIdeal']} ms)")


if __name__ == "__main__":
    main()
