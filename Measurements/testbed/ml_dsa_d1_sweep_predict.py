#!/usr/bin/env python3
"""ml_dsa_d1_sweep_predict.py - pre-registration of the ML-DSA-65 depth-1 sweep (results/mldsa_d1_sweep_configs.csv, results/mldsa_d1_sweep_predictions.md).
COMMIT AND PUSH BEFORE THE MEASUREMENT.
Observation (three machines, 15/11/2026): in the cells ML-DSA-65|ML-KEM-768, depth 1, mTLS, request 302 B, RTT 30 ms, 100 Mbit/s, MTU 1500, icw 10, Reno,
the measured time is already one RTT above the model at response 22 500 B (IPv6 and IPv4), where the model has the transition at 22 900-23 000 B (IPv6) and 23 300-23 400 B (IPv4).
Hypothesis H1: the model counts too few bytes in this flight (undercount D, like the 2.4 kB found in G3b at MTU 9000), so the measured transition lies D bytes below the model one in both IP versions.
Sweep: response 17 000 to 22 400 B in steps of 200 (28 values) x IPv6, IPv4 (PQC_IP=4), n=30, same configuration otherwise. t = first response size whose median excess is more than 15 ms above the one 200 B below."""
import csv, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import analyze_testbed as A
S = A.S
SUITE = "ML-DSA-65|ML-KEM-768"; RESP = list(range(17000, 22401, 200))
def ex(resp, h, shift=0):
    fl = S.build_flow(SUITE, A.probe_protocol("1", "302", str(resp + shift), "1"), 1, "cold", False)
    n = S.Net(100.0, 30.0, 1500, penalty_ms=0.0, thr=4, init_cwnd=10, cwnd_validation=True, segmentation="openssl", cwnd_slack=0, hdr=h)
    r = S.run_flow(fl, n); return r["total"] - r["cpu"]
def first_jump(h, shift, lo, hi):
    prev = None
    for r in range(lo, hi + 1, 100):
        v = ex(r, h, shift)
        if prev is not None and v - prev > 15: return r
        prev = v
cfg = [dict(suite=SUITE, depth=1, mtls=1, req=302, resp=r, rtt_ms=30, rate_mbps=100, mtu=1500, icw=10, loss_pct=0, cc="reno") for r in RESP]
w = csv.DictWriter(open(os.path.join(HERE, "results", "mldsa_d1_sweep_configs.csv"), "w", newline=""), fieldnames=list(cfg[0])); w.writeheader(); w.writerows(cfg)
m6, m4 = first_jump(60, 0, 15000, 30000), first_jump(40, 0, 15000, 30000)
rows = [("model as it is (D=0)", 0)] + [(f"H1 with D={d} B", d) for d in (1200, 2400)]
L = ["# ML-DSA-65 depth 1 sweep: pre-registered predictions (generated by ml_dsa_d1_sweep_predict.py before the measurement)", "",
     f"Model transition (first response size, resolution 100 B): IPv6 {m6}, IPv4 {m4} (difference {m4 - m6} B).", "",
     "| hypothesis | IPv6 t6 (B) | IPv4 t4 (B) | t4 - t6 |", "|---|---|---|---|"]
for name, d in rows:
    a, b = first_jump(60, d, 15000, 30000), first_jump(40, d, 15000, 30000)
    L.append(f"| {name} | {a} | {b} | {b - a} |")
L += ["", "Criteria (scored by analyze_mldsa_sweep.py on the sweep, per machine):",
      "- S1 a transition (excess +20 to +35 ms against the cell 200 B below) exists below 22 500 B for IPv6: H1 predicted, a failure to find one rejects any byte undercount.",
      f"- S2 t4 - t6 = {m4 - m6} B within +-200 B (header effect, independent of D): met supports a byte undercount; t4 - t6 close to 0 points to another mechanism (record count, write pattern).",
      "- S3 t6 within 400 B of 20 600 B (= model - 2 400 B, the G3b undercount): met supports that G3b and this have the same cause; a different t6 gives an undercount D = model t6 - measured t6 of its own.",
      "- The sweep says nothing about ECDSA cells (they agree with the model)."]
open(os.path.join(HERE, "results", "mldsa_d1_sweep_predictions.md"), "w").write("\n".join(L) + "\n"); print("\n".join(L))
