#!/usr/bin/env python3
"""
capacity_test.py - TLS 1.3 server capacity (handshakes per second and CPU per handshake), paper 2 (WP2). No root, no network namespaces.

    python3 capacity_test.py --out results/capacity_<machine>.csv [--suites ...] [--depths 1,2,3,4] [--mtls 0,1] [--resume 0,1]
                             [--server-cores 1,2,4] [--procs-per-core 4] [--time 8] [--warmup 2]

Method. For every configuration it starts `tls_probe server --reuseport` processes, procs-per-core of them pinned to each of the
server cores (a blocking single-connection server waits for the client most of the time; several processes per core keep the core
saturated), and runs `tls_load` on the other cores until the server cores are busy. Counters are read from the server processes
with SIGUSR1 at the start and the end of the measurement window:
    cpu_ms_per_hs   user + system CPU time of the server processes / handshakes completed in the window (TCP, TLS and crypto)
    rate_per_s      transactions completed per second at saturation (client side, handshake + one request/response)
    util            server CPU use / (cores x window): below about 0.9 the CLIENT or the kernel limits the rate, not the server.
Chains come from ../certs (generated by ../certs.sh; the keys are not in the repository). Loopback only: the cost of the real network
path (interrupts, NIC) is not in these numbers.
"""
from __future__ import annotations

import argparse
import csv
import os
import signal
import subprocess
import sys
import threading
import time

HERE = os.path.dirname(os.path.abspath(__file__))
MEAS = os.path.dirname(HERE)
sys.path.insert(0, MEAS)
sys.path.insert(0, HERE)
import run_testbed as RT  # noqa: E402  (ensure_chain, suite table)
from tls_trace import SUITES as ALL_SUITES  # noqa: E402

DEFAULT_SUITES = ["ECDSA-P256|X25519", "ECDSA-P256|X25519MLKEM768", "RSA-2048|ECDHE-P256", "ML-DSA-44|ML-KEM-768",
                  "ML-DSA-65|ML-KEM-768", "ML-DSA-87|ML-KEM-1024"]
COLS = ["machine", "server", "suite", "depth", "mtls", "resume", "server_cores", "procs", "client_threads", "ok", "err", "rate_per_s",
        "rate_per_core", "cpu_ms_per_hs", "system_frac", "util", "p50_ms", "p99_ms", "first_error"]


def topology():
    """{physical core: [logical cpus]} from lscpu."""
    out = subprocess.run(["lscpu", "-p=CPU,CORE,SOCKET"], capture_output=True, text=True, check=True).stdout
    cores = {}
    for line in out.splitlines():
        if line.startswith("#") or not line.strip():
            continue
        cpu, core, sock = line.split(",")[:3]
        cores.setdefault((int(sock), int(core)), []).append(int(cpu))
    return [sorted(v) for _, v in sorted(cores.items())]


def cpu_list(cpus):
    return ",".join(map(str, cpus))


class Server:
    def __init__(self, cmd, cpu):
        self.p = subprocess.Popen(["taskset", "-c", str(cpu)] + cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        self.lines = []
        self.cv = threading.Condition()
        threading.Thread(target=self._read, daemon=True).start()
        self.wait("READY", 10)

    def _read(self):
        for line in self.p.stdout:
            with self.cv:
                self.lines.append(line.strip())
                self.cv.notify_all()

    def wait(self, prefix, timeout, start=0):
        end = time.time() + timeout
        with self.cv:
            while True:
                for l in self.lines[start:]:
                    if l.startswith(prefix):
                        return l
                left = end - time.time()
                if left <= 0:
                    raise RuntimeError(f"server did not print {prefix}: {self.p.stderr.read(400) if self.p.poll() is not None else ''}")
                self.cv.wait(left)

    def stats(self):
        n = len(self.lines)
        self.p.send_signal(signal.SIGUSR1)
        l = self.wait("STATS", 5, n)
        p = l.split(",")
        return int(p[1]), float(p[2]), float(p[3])      # transactions completed, user cpu s, system cpu s (a fifth field, handshakes, may follow)

    def stop(self):
        self.p.terminate()
        try:
            self.p.wait(5)
        except subprocess.TimeoutExpired:
            self.p.kill()


def run_config(a, topo, machine, suite, depth, mtls, resume, ncores, port):
    alg, group = ALL_SUITES[suite]
    ch = RT.ensure_chain(alg, depth, os.path.join(HERE, "work"))
    if a.server_cpus:                                                  # explicit lists (needed on big.LITTLE machines such as the Arm test platform)
        server_cpus = a.server_cpus[:ncores]
        client_cpus = a.client_cpus
    else:
        server_cpus = [t[0] for t in topo[:ncores]]
        busy = {c for t in topo[:ncores] for c in t}                   # server cores and their SMT siblings stay free of the client
        client_cpus = [c for t in topo for c in t if c not in busy]
        if not client_cpus:
            client_cpus = [c for t in topo for c in t if c not in server_cpus]
    scmd = [os.path.join(HERE, a.server)] + (["server"] if a.server == "tls_probe" else []) + ["--addr", "127.0.0.1", "--port", str(port), "--cert", ch["server"][0],
            "--key", ch["server"][1], "--ca", ch["ca"], "--groups", group, "--req", str(a.req), "--resp", str(a.resp), "--reuseport"]
    scmd += (["--mtls"] if mtls else []) + (["--resume"] if resume else [])
    servers = [Server(scmd, c) for c in server_cpus for _ in range(a.procs_per_core)]
    nthreads = a.client_threads or max(8, 4 * len(client_cpus))
    ccmd = ["taskset", "-c", cpu_list(client_cpus), os.path.join(HERE, "tls_load"), "--addr", "127.0.0.1", "--port", str(port), "--ca", ch["ca"],
            "--groups", group, "--req", str(a.req), "--resp", str(a.resp), "--threads", str(nthreads), "--time", str(a.time),
            "--warmup", str(a.warmup)] + (["--cert", ch["client"][0], "--key", ch["client"][1]] if mtls else []) + (["--resume"] if resume else [])
    cl = subprocess.Popen(ccmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    try:
        time.sleep(a.warmup + 0.3)
        s0 = [s.stats() for s in servers]
        w0 = time.time()
        time.sleep(a.time - 0.6)
        s1 = [s.stats() for s in servers]
        w1 = time.time()
        out, err = cl.communicate(timeout=a.time + a.warmup + 60)
    finally:
        for s in servers:
            s.stop()
        if cl.poll() is None:
            cl.kill()
    rows = out.strip().splitlines()
    if len(rows) < 2:
        raise RuntimeError("tls_load failed: " + err[-300:])
    r = dict(zip(rows[0].split(","), rows[1].split(",")))
    hs = sum(b[0] - a_[0] for a_, b in zip(s0, s1))
    cpu = sum((b[1] + b[2]) - (a_[1] + a_[2]) for a_, b in zip(s0, s1))
    sysc = sum(b[2] - a_[2] for a_, b in zip(s0, s1))
    win = w1 - w0
    ok, tl = int(r["ok"]), float(r["time_s"])
    return dict(machine=machine, server=a.server, suite=suite, depth=depth, mtls=mtls, resume=resume, server_cores=ncores, procs=len(servers),
                client_threads=nthreads, ok=ok, err=int(r["err"]), rate_per_s=round(ok / tl, 1), rate_per_core=round(ok / tl / ncores, 1),
                cpu_ms_per_hs=round(1000 * cpu / hs, 4) if hs else "", system_frac=round(sysc / cpu, 3) if cpu else "",
                util=round(cpu / (ncores * win), 3), p50_ms=r["p50_ms"], p99_ms=r["p99_ms"], first_error=r["first_error"])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(HERE, "results", "capacity.csv"))
    ap.add_argument("--machine", default=os.uname().nodename)
    ap.add_argument("--suites", default=",".join(DEFAULT_SUITES))
    ap.add_argument("--depths", default="1,2,3,4")
    ap.add_argument("--mtls", default="0,1")
    ap.add_argument("--resume", default="0,1")
    ap.add_argument("--server-cores", default="1")
    ap.add_argument("--server-cpus", default="", help="logical CPUs for the server cores, e.g. 18,19,16,17 (default: first threads of the first physical cores)")
    ap.add_argument("--client-cpus", default="", help="logical CPUs for the load generator, e.g. 5,6,7,8,9,15")
    ap.add_argument("--server", choices=["tls_serve", "tls_probe"], default="tls_serve", help="tls_serve: event-driven (default); tls_probe: blocking, one connection at a time")
    ap.add_argument("--procs-per-core", type=int, default=0, help="server processes per core (default 1 for tls_serve, 4 for tls_probe)")
    ap.add_argument("--client-threads", type=int, default=0)
    ap.add_argument("--req", type=int, default=302)
    ap.add_argument("--resp", type=int, default=222)
    ap.add_argument("--time", type=float, default=8.0)
    ap.add_argument("--warmup", type=float, default=2.0)
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    topo = topology()
    a.procs_per_core = a.procs_per_core or (1 if a.server == "tls_serve" else 4)
    a.server_cpus = [int(x) for x in a.server_cpus.split(",")] if a.server_cpus else []
    a.client_cpus = [int(x) for x in a.client_cpus.split(",")] if a.client_cpus else []
    if bool(a.server_cpus) != bool(a.client_cpus):
        sys.exit("give both --server-cpus and --client-cpus, or neither")
    suites, depths = a.suites.split(","), [int(x) for x in a.depths.split(",")]
    cores = [int(x) for x in a.server_cores.split(",")]
    cfgs = [(su, d, m, r, c) for su in suites for d in depths for m in [int(x) for x in a.mtls.split(",")]
            for r in [int(x) for x in a.resume.split(",")] for c in cores if not (r and d != depths[0])]   # a resumed handshake does not depend on the chain depth (the ticket carries the leaf only)
    est = len(cfgs) * (a.time + a.warmup + 3) / 60
    print(f"{len(cfgs)} configurations, about {est:.0f} min; {len(topo)} physical cores: {topo}")
    if a.list:
        return
    for b in (a.server, "tls_load"):
        if not os.path.exists(os.path.join(HERE, b)):
            sys.exit(f"{b} not built: run ./setup_host.sh")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    done = set()
    new = not os.path.exists(a.out)
    if not new:
        for r in csv.DictReader(open(a.out)):
            if r.get("server") == a.server:
                done.add((r["suite"], int(r["depth"]), int(r["mtls"]), int(r["resume"]), int(r["server_cores"])))
    fh = open(a.out, "a", newline="")
    w = csv.DictWriter(fh, fieldnames=COLS)
    if new:
        w.writeheader()
    port = 47000
    for i, cfg in enumerate(cfgs, 1):
        if cfg in done:
            continue
        port += 1
        try:
            row = run_config(a, topo, a.machine, *cfg, port)
        except Exception as e:                       # keep going; the configuration stays unfinished
            print(f"[{i}/{len(cfgs)}] {cfg} FAILED: {e}", flush=True)
            continue
        w.writerow(row)
        fh.flush()
        print(f"[{i}/{len(cfgs)}] {cfg}: {row['rate_per_s']:.0f}/s, {row['cpu_ms_per_hs']} ms CPU per handshake, util {row['util']}, err {row['err']}", flush=True)
    fh.close()


if __name__ == "__main__":
    main()
